"""
Users Database Models.
This file defines the SQLModel tables that represent exactly how data is stored 
in the relational database (MySQL) for the "Users" feature.
"""

# ---------------------------------------------------------
# External Imports
# ---------------------------------------------------------
from typing import Optional
from sqlmodel import Field

# ---------------------------------------------------------
# Internal Imports
# ---------------------------------------------------------
from features.users.schemas import UserBase

class User(UserBase, table=True):
    """
    The main User database table.
    Inherits fields like 'email' and 'is_active' from UserBase, 
    and adds database-specific fields like the primary key 'id' and 'hashed_password'.
    """
    # Explicitly name the table in MySQL to avoid auto-generated pluralization issues
    __tablename__ = "users"
    
    # The primary key for the database table, automatically generated by the database
    id: Optional[int] = Field(default=None, primary_key=True)
    
    # The hashed password string (we never store plain text passwords in the database)
    hashed_password: str
